import CommunityMembersMobileSortContent from "@/components/community/members-table/CommunityMembersMobileSortContent";
import CommunityMembersTable from "@/components/community/members-table/CommunityMembersTable";
import { SortDirection } from "@/entities/ISort";
import type { ApiCommunityMemberOverview } from "@/generated/models/ApiCommunityMemberOverview";
import { ApiCommunityMembersSortOption } from "@/generated/models/ApiCommunityMembersSortOption";
import { useMediaQuery } from "@/hooks/useMediaQuery";
import { render, screen, within } from "@testing-library/react";
import type { ReactNode } from "react";

const mockXtdhRetired = jest.fn(() => false);

jest.mock("@/hooks/useXtdhRetirement", () => ({
  useXtdhRetired: () => mockXtdhRetired(),
}));
jest.mock("@/hooks/useMediaQuery", () => ({ useMediaQuery: jest.fn() }));
jest.mock("next/link", () => ({
  __esModule: true,
  default: ({ href, children }: { href: string; children: ReactNode }) => (
    <a href={href}>{children}</a>
  ),
}));
jest.mock("@/helpers/Helpers", () => ({
  formatNumberWithCommasOrDash: (n: number) => `#${n}`,
  formatLargeNumber: (n: number) => `${n}L`,
  getTimeAgoShort: () => "2h",
}));
jest.mock("@/helpers/AllowlistToolHelpers", () => ({
  isEthereumAddress: (val: string) => val.startsWith("0x"),
  isAutoGeneratedHandle: () => false,
}));
jest.mock("@/helpers/image.helpers", () => ({
  ImageScale: { W_AUTO_H_50: "50" },
  getScaledImageUri: (url: string) => url,
}));
jest.mock("@/components/user/utils/UserCICAndLevel", () => ({
  __esModule: true,
  default: () => <div data-testid="level" />,
  UserCICAndLevelSize: { MEDIUM: "MEDIUM" },
}));
jest.mock("@/components/user/utils/level/UserLevel", () => ({
  __esModule: true,
  default: () => <div data-testid="level" />,
}));
jest.mock("@/components/user/utils/user-cic-type/UserCICTypeIcon", () => ({
  __esModule: true,
  default: () => <div data-testid="cic-icon" />,
}));

const member: ApiCommunityMemberOverview = {
  display: "Alice",
  detail_view_key: "alice",
  level: 1,
  tdh: 100,
  tdh_rate: 10,
  xtdh: 777,
  xtdh_rate: 5,
  combined_tdh: 877,
  combined_tdh_rate: 15,
  rep: 60,
  cic: 1,
  pfp: null,
  last_activity: null,
  wallet: "0x0000000000000000000000000000000000000001",
  xtdh_outgoing: 0,
  xtdh_incoming: 0,
};

const renderTable = () =>
  render(
    <CommunityMembersTable
      members={[member]}
      activeSort={ApiCommunityMembersSortOption.Level}
      sortDirection={SortDirection.DESC}
      page={1}
      pageSize={50}
      isLoading={false}
      onSort={jest.fn()}
    />
  );

describe("community members once xTDH is retired", () => {
  beforeEach(() => {
    mockXtdhRetired.mockReturnValue(false);
  });

  it("shows the xTDH column while xTDH is live", () => {
    jest.mocked(useMediaQuery).mockReturnValue(true);
    renderTable();
    const headers = screen.getAllByRole("columnheader");
    expect(headers.map((h) => h.textContent)).toContain("xTDH");
    expect(screen.getByText("777L")).toBeInTheDocument();
    const row = screen.getAllByRole("row")[1]!;
    expect(within(row).getAllByRole("cell")).toHaveLength(headers.length);
  });

  it("drops the xTDH column and keeps rows aligned", () => {
    mockXtdhRetired.mockReturnValue(true);
    jest.mocked(useMediaQuery).mockReturnValue(true);
    renderTable();
    const headers = screen.getAllByRole("columnheader");
    expect(headers.map((h) => h.textContent)).not.toContain("xTDH");
    expect(screen.queryByText("777L")).toBeNull();
    const row = screen.getAllByRole("row")[1]!;
    expect(within(row).getAllByRole("cell")).toHaveLength(headers.length);
  });

  it("drops the xTDH figure from the mobile card", () => {
    jest.mocked(useMediaQuery).mockReturnValue(false);
    const { unmount } = renderTable();
    expect(screen.getByText("xTDH")).toBeInTheDocument();
    unmount();

    mockXtdhRetired.mockReturnValue(true);
    renderTable();
    expect(screen.queryByText("xTDH")).toBeNull();
    expect(screen.queryByText("777L")).toBeNull();
    expect(screen.getByText("TDH")).toBeInTheDocument();
  });

  it("drops the xTDH sort from the mobile sort list", () => {
    mockXtdhRetired.mockReturnValue(true);
    render(
      <CommunityMembersMobileSortContent
        activeSort={ApiCommunityMembersSortOption.Level}
        sortDirection={SortDirection.DESC}
        onSort={jest.fn()}
      />
    );
    expect(screen.queryByText("xTDH")).toBeNull();
    expect(screen.getByText("TDH")).toBeInTheDocument();
    expect(screen.getByText("REP")).toBeInTheDocument();
  });
});
