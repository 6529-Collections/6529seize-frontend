#!/usr/bin/env node
/**
 * Writes the 6529 Explained fixtures (`lib/explained/fixtures/`): the public
 * TDH feed as fetched on 2026-10-18 (index.json and five day files, kept as
 * their exact text in `feedFixture.ts`, so a file's SHA-256 can be computed
 * from it) and the Meme editions as 6529.io's API reported them
 * (`editions.json`), so the kit gallery and the tests render the same day
 * the mockups do. Every day file's SHA-256 is checked against the index
 * before it is written; a mismatch fails.
 *
 *   node scripts/explained/make-fixtures.mjs --from <design data folder>
 *
 * The folder holds `feed/index.json`, `feed/days/{cycle}.json` and
 * `memes-editions.json`. Public data only: no address, no holder.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);
const OUT = path.join(ROOT, "lib/explained/fixtures");

const fromIndex = process.argv.indexOf("--from");
if (fromIndex === -1 || !process.argv[fromIndex + 1]) {
  console.error("usage: make-fixtures.mjs --from <design data folder>");
  process.exit(2);
}
const FROM = path.resolve(process.argv[fromIndex + 1]);
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");

mkdirSync(OUT, { recursive: true });
const indexText = readFileSync(path.join(FROM, "feed/index.json"), "utf8");
const index = JSON.parse(indexText);
const dayTexts = {};
for (const day of index.days) {
  const bytes = readFileSync(path.join(FROM, `feed/days/${day.cycleDay}.json`));
  if (sha(bytes) !== day.sha256) {
    throw new Error(`days/${day.cycleDay}.json does not match the index`);
  }
  const text = bytes.toString("utf8");
  if (
    Buffer.from(text, "utf8").compare(bytes) !== 0 ||
    /[^\t\n\x20-\x7e]/.test(text)
  ) {
    throw new Error(`days/${day.cycleDay}.json is not plain ASCII text`);
  }
  dayTexts[day.cycleDay] = text;
}
const module = [
  "/**",
  " * The public TDH feed as fetched on 2026-10-18, each file's exact text.",
  " * Generated by scripts/explained/make-fixtures.mjs; do not edit: each day",
  " * file's SHA-256 must equal the one its index states.",
  " */",
  `export const FIXTURE_INDEX_TEXT = ${JSON.stringify(indexText)};`,
  "",
  "export const FIXTURE_DAY_TEXTS: Readonly<Record<number, string>> = {",
  ...Object.entries(dayTexts).map(
    ([cycle, text]) => `  ${cycle}: ${JSON.stringify(text)},`
  ),
  "};",
  "",
].join("\n");
writeFileSync(path.join(OUT, "feedFixture.ts"), module);

const editions = JSON.parse(
  readFileSync(path.join(FROM, "memes-editions.json"), "utf8")
);
const compact = {
  note: "The Memes as 6529.io's API reported them: [id, season, copies minted, first mint (UTC)]. Generated by scripts/explained/make-fixtures.mjs.",
  readAt: editions.fetchedAt,
  source: "6529.io API memes_extended_data",
  cards: editions.cards.map((card) => [
    card.id,
    card.season,
    card.supply,
    card.mint_date.slice(0, 19) + "Z",
  ]),
};
writeFileSync(path.join(OUT, "editions.json"), `${JSON.stringify(compact)}\n`);
console.log(
  `wrote ${index.days.length} day files and index.json (feedFixture.ts) and ${compact.cards.length} editions to ${path.relative(ROOT, OUT)}`
);
