"use strict";

// Run with ./bin/6529 exec node scripts/generate-version-reload-image.cjs
// Keep the loading-screen artwork in sync when the source rocket changes.
// The WebP is a static file in public/ whose name carries a content hash, so the
// reload cover can cache it indefinitely (see config/versionReloadImageHeaders.ts)
// and the HTML only carries its short URL instead of the image bytes.
const { createHash } = require("node:crypto");
const {
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");

const ARTWORK_PREFIX = "version-reload-rocket";
const HASH_LENGTH = 12;

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function generate() {
  const root = path.resolve(__dirname, "..");
  const publicDir = path.join(root, "public");
  const source = readFileSync(path.join(publicDir, "rocket-refresh-small.png"));
  // 60 CSS pixels at 3x density, with transparency and the original green artwork.
  const image = await sharp(source)
    .resize(180, 180, { fit: "inside" })
    .webp({ quality: 90 })
    .toBuffer();
  const fileName = `${ARTWORK_PREFIX}.${sha256(image).slice(0, HASH_LENGTH)}.webp`;

  for (const existing of readdirSync(publicDir)) {
    if (
      existing.startsWith(`${ARTWORK_PREFIX}.`) &&
      existing.endsWith(".webp") &&
      existing !== fileName
    ) {
      unlinkSync(path.join(publicDir, existing));
    }
  }
  writeFileSync(path.join(publicDir, fileName), image);

  const output = `// Generated by scripts/generate-version-reload-image.cjs. Do not edit.\n// Source SHA-256: ${sha256(source)}\nexport const VERSION_RELOAD_IMAGE_SRC =\n  "/${fileName}";\n`;
  writeFileSync(
    path.join(root, "components/version-update/versionReloadImage.ts"),
    output
  );
  console.log(`Reload rocket: public/${fileName} (${image.length} bytes)`);
}

generate().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
