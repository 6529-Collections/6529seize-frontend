"use strict";

// Run with ./bin/6529 exec node scripts/generate-version-reload-image.cjs
// Keep the version-update artwork in sync when a source rocket changes.
// Each WebP is a static file in public/ whose name carries a content hash, so
// it can be cached indefinitely (see config/versionReloadImageHeaders.ts) and
// the UI references a small image instead of the full-size source PNG.
const { createHash } = require("node:crypto");
const {
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");

const HASH_LENGTH = 12;

const ARTWORKS = [
  {
    // Reload cover, docked and sidebar update buttons: 60 CSS pixels at 3x
    // density, with transparency and the original green artwork.
    exportName: "VERSION_RELOAD_IMAGE_SRC",
    prefix: "version-reload-rocket",
    source: "rocket-refresh-small.png",
    resize: { width: 180, height: 180, fit: "inside" },
  },
  {
    // New-version toast: shown 48 CSS pixels tall, kept at 3x density. The
    // toast reserves the matching width, emitted here so it follows the art.
    exportName: "VERSION_UPDATE_ROCKET_IMAGE_SRC",
    prefix: "version-update-rocket",
    source: "rocket-refresh.png",
    resize: { height: 144, fit: "inside" },
    displayWidth: {
      exportName: "VERSION_UPDATE_ROCKET_IMAGE_WIDTH",
      cssHeight: 48,
    },
  },
];

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function generateArtwork(publicDir, artwork) {
  const source = readFileSync(path.join(publicDir, artwork.source));
  const image = await sharp(source)
    .resize(artwork.resize)
    .webp({ quality: 90 })
    .toBuffer();
  const fileName = `${artwork.prefix}.${sha256(image).slice(0, HASH_LENGTH)}.webp`;

  for (const existing of readdirSync(publicDir)) {
    if (
      existing.startsWith(`${artwork.prefix}.`) &&
      existing.endsWith(".webp") &&
      existing !== fileName
    ) {
      unlinkSync(path.join(publicDir, existing));
    }
  }
  writeFileSync(path.join(publicDir, fileName), image);
  console.log(
    `${artwork.exportName}: public/${fileName} (${image.length} bytes)`
  );

  let output = `// Source SHA-256: ${sha256(source)}\nexport const ${artwork.exportName} =\n  "/${fileName}";\n`;
  if (artwork.displayWidth) {
    const { width, height } = await sharp(image).metadata();
    const { cssHeight, exportName } = artwork.displayWidth;
    const cssWidth = Math.round((width * cssHeight) / height);
    output += `// CSS width at ${cssHeight}px tall.\nexport const ${exportName} = ${cssWidth};\n`;
  }
  return output;
}

async function generate() {
  const root = path.resolve(__dirname, "..");
  const publicDir = path.join(root, "public");
  const exports = [];
  for (const artwork of ARTWORKS) {
    exports.push(await generateArtwork(publicDir, artwork));
  }

  writeFileSync(
    path.join(root, "components/version-update/versionReloadImage.ts"),
    `// Generated by scripts/generate-version-reload-image.cjs. Do not edit.\n${exports.join("")}`
  );
}

generate().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
