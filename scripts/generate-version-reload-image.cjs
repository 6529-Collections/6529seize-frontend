"use strict";

// Run with ./bin/6529 exec node scripts/generate-version-reload-image.cjs
// Keep the loading-screen artwork in sync when the source rocket changes.
const { createHash } = require("node:crypto");
const { readFileSync, writeFileSync } = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");

async function generate() {
  const root = path.resolve(__dirname, "..");
  const source = readFileSync(
    path.join(root, "public/rocket-refresh-small.png")
  );
  const hash = createHash("sha256").update(source).digest("hex");
  // 60 CSS pixels at 3x density, with transparency and the original green artwork.
  const image = await sharp(source)
    .resize(180, 180, { fit: "inside" })
    .webp({ quality: 90 })
    .toBuffer();
  const output = `// Generated by scripts/generate-version-reload-image.cjs. Do not edit.\n// Source SHA-256: ${hash}\nexport const VERSION_RELOAD_IMAGE_DATA =\n  "data:image/webp;base64,${image.toString("base64")}";\n`;
  writeFileSync(
    path.join(root, "components/version-update/versionReloadImage.ts"),
    output
  );
  console.log(`Embedded reload rocket: ${image.length} bytes`);
}

generate().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
